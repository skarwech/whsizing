def test_a_series_too_short_to_split_is_an_error() -> None:
    with pytest.raises(DataQualityError, match=f"at least {MIN_FIT_MONTHS + 3}"):
        split_months(np.ones(5), 3)
    with pytest.raises(ConfigError, match="at least 1"):
        split_months(np.ones(12), 0)
    assert split_months(np.arange(1.0, 7.0), 3).fit == (0, 1, 2)


