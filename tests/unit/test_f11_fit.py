MONTHS = tuple(f"2025-{m:02d}" for m in range(1, 13))
TOLERANCE = 0.05  # T11.1


@pytest.fixture(scope="module")
def base() -> Baseline:
    return baseline_monthly(site_inputs())


def effective(fit_theta, name: str) -> float:
    return next(t.effective for t in fit_theta if t.name == f"m:{name}")


def raw(fit_theta, name: str) -> float:
    return next(t.fitted for t in fit_theta if t.name == f"m:{name}")


# --- T11.1: known multipliers are recovered ------------------------------------------------------


def test_T11_1_fit_recovers_known_multipliers_within_5_percent(base: Baseline) -> None:
    """Actuals generated by the predictor with KNOWN multipliers (both sides of 1) and 2 % noise:
    every fitted multiplier is within 5 % of the truth (the raw θ and the identified effective
    multiplier alike, PF&D at its basis value)."""
    fit = fit_site(base, synthetic_actuals(base, KNOWN, MONTHS))
    assert fit.status > 0 and fit.split.holdout == (9, 10, 11)
    for g, truth in KNOWN.items():
        assert raw(fit.theta, g) == pytest.approx(truth, rel=TOLERANCE), g
        assert effective(fit.theta, g) == pytest.approx(truth, rel=TOLERANCE), g
    assert fit.eta == pytest.approx(base.eta)  # does not enter the hours: stays at its prior


@pytest.mark.parametrize(
    "truth",
    [
        dict.fromkeys(KNOWN, 1.3),  # all above 1: the prior pulls PF&D, the effective ones hold
        {**dict.fromkeys(KNOWN, 0.8), "picking": 1.4, "packing": 1.15},
    ],
)
def test_T11_1_effective_multipliers_are_recovered_when_the_prior_pulls_pfd(
    base: Baseline, truth: dict[str, float]
) -> None:
    fit = fit_site(base, synthetic_actuals(base, truth, MONTHS))
    for g, m in truth.items():
        assert effective(fit.theta, g) == pytest.approx(m, rel=TOLERANCE), g


def test_T11_1_pfd_is_confounded_with_the_multipliers(base: Baseline) -> None:
    """Hours generated with PF&D 0.20 and m: the identified (effective) multiplier is
    m × (1.12 / 1.20), whatever split of the two the prior picks."""
    truth = {g: m for g, m in KNOWN.items() if g != INDIRECT}
    fit = fit_site(base, synthetic_actuals(base, truth, MONTHS, noise=0.0, pfd=0.2))
    for g, m in truth.items():
        assert effective(fit.theta, g) == pytest.approx(m * 1.12 / 1.2, rel=0.01), g
    pfd = next(t for t in fit.theta if t.name == "pfd")
    assert not pfd.identified and "confounded" in pfd.note


